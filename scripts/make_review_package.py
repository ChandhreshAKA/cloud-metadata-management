"""Build docs/03-review-package.md: everything an outside reviewer needs to check the selection
engine, generated from the code itself so the numbers cannot drift from the implementation.

    .venv\\Scripts\\python.exe scripts\\make_review_package.py

No database, no network. ALL PRICES, SCORES AND LATENCIES ARE ILLUSTRATIVE.
"""

from __future__ import annotations

import json
import sys
from dataclasses import replace
from decimal import Decimal as D
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from app.selection import serialize  # noqa: E402
from app.selection.baselines import cheapest_only, fixed_provider  # noqa: E402
from app.selection.engine import select  # noqa: E402
from app.selection.example import EXAMPLE_CANDIDATES, EXAMPLE_REQUEST  # noqa: E402
from app.selection.explain import fmt  # noqa: E402
from app.selection.models import Candidate  # noqa: E402
from app.selection.presets import DEFAULT_POLICY, PRESETS  # noqa: E402

CODE_FILES = [
    "app/selection/models.py",
    "app/selection/engine.py",
    "app/selection/presets.py",
    "app/selection/explain.py",
    "app/selection/baselines.py",
    "app/selection/example.py",
]


def inputs_table(candidates: list[Candidate]) -> str:
    head = (
        "| region_id | provider (region) | enabled | health | storage $/GB-mo | put $/1k | get $/1k "
        "| retrieval $/GB | egress $/GB | min days | latency ms | reliability | security | max object bytes |\n"
        "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|\n"
    )
    rows = []
    for c in candidates:
        p = c.pricing
        rows.append(
            f"| {c.region_id} | {c.label} | {c.provider_active and c.region_active} | {c.health_status} "
            f"| {fmt(p.storage_usd_per_gb_month)} | {fmt(p.put_usd_per_1k)} | {fmt(p.get_usd_per_1k)} "
            f"| {fmt(p.retrieval_usd_per_gb)} | {fmt(c.egress_usd_per_gb)} | {p.min_storage_days} "
            f"| {fmt(c.latency_ms)} | {fmt(c.reliability_score)} | {fmt(c.security_score)} "
            f"| {c.max_object_bytes} |"
        )
    return head + "\n".join(rows) + "\n"


def policy_table() -> str:
    lines = [
        "| file security level | min security score | min reliability score |",
        "|---|---|---|",
    ]
    for level in ("LOW", "MEDIUM", "HIGH"):
        lines.append(
            f"| {level} | {fmt(DEFAULT_POLICY.min_security[level])} "
            f"| {fmt(DEFAULT_POLICY.min_reliability[level])} |"
        )
    return "\n".join(lines) + "\n"


def weights_table() -> str:
    lines = [
        "| preset | storage_cost | transfer_cost | latency | reliability | security |",
        "|---|---|---|---|---|---|",
    ]
    for name, w in PRESETS.items():
        lines.append(f"| {name} | " + " | ".join(fmt(v) for v in w.as_dict().values()) + " |")
    return "\n".join(lines) + "\n"


def run(case_candidates, request, preset):
    result = select(request, case_candidates, PRESETS[preset], DEFAULT_POLICY, preset_name=preset)
    payload = serialize.result_dict(result, preset)
    payload["baselines"] = {
        "cheapest_only": serialize.baseline_dict(
            cheapest_only(request, case_candidates, DEFAULT_POLICY)
        ),
        "fixed_provider_GCP": serialize.baseline_dict(
            fixed_provider(request, case_candidates, DEFAULT_POLICY, "GCP")
        ),
    }
    return json.dumps(payload, indent=2)


def main() -> None:
    req = EXAMPLE_REQUEST
    # Case B: the same three providers plus two that must be REJECTED (to show rejection reasons)
    down = replace(
        EXAMPLE_CANDIDATES[0], region_id=4, provider_id=4, provider_code="OCI", provider_name="Oracle Cloud",
        region_code="ap-hyderabad-1", health_status="DOWN", latency_ms=D("5"),
    )  # fmt: skip
    weak_and_small = replace(
        EXAMPLE_CANDIDATES[1], region_id=5, provider_id=5, provider_code="TINY", provider_name="TinyCloud",
        region_code="local-1", security_score=D("7.5"), max_object_bytes=1024**3,
    )  # fmt: skip
    case_b = [*EXAMPLE_CANDIDATES, down, weak_and_small]

    out: list[str] = []
    add = out.append
    add("# Selection engine review package\n")
    add(
        "Generated by `scripts/make_review_package.py` from the code in this repository. **Every price, "
        "score and latency here is ILLUSTRATIVE (invented for demonstration).** Nothing below was typed by "
        "hand: the tables and JSON are the program's own output.\n"
    )
    add("## 1. How to read this package\n")
    add(
        "* The engine is the pure function `select(request, candidates, weights, policy)` in "
        "`app/selection/engine.py` (full source in section 6). There is **no `criteria.py`**: "
        "normalisation (`normalise`), constraints (`check_constraints`) and the cost calculation "
        "(`estimate_cost`) are all in `engine.py`; data types are in `models.py`.\n"
        "* A candidate is a **provider-region**.\n"
        "* Rounding: money to 8 decimals, normalised values and composites to 6 decimals, "
        "`ROUND_HALF_EVEN`, using `decimal.Decimal` (no floats).\n"
    )

    add("## 2. Raw inputs, case A (the worked example)\n")
    add(
        f"File: **{req.file_size_bytes} bytes (10 GiB)**, security level **{req.security_level}**, tier "
        f"**{req.tier}**, kept **{fmt(req.retention_months)} months**, **{fmt(req.expected_accesses_per_month)} "
        "reads per month** (so 48 reads over the retention period).\n"
    )
    add(inputs_table(list(EXAMPLE_CANDIDATES)))
    add("\nHard-constraint minimums used (from `DEFAULT_POLICY`):\n")
    add(policy_table())
    add("\nProvider size limit is the `max object bytes` column (5 TiB each here).\n")

    add("## 3. Weights used, and the preset\n")
    add(
        "Case A uses the preset **BALANCED** (0.25 / 0.15 / 0.20 / 0.25 / 0.15). All presets, "
        "each summing to 1, as stored in the `weight_profiles` table:\n"
    )
    add(weights_table())

    add("\n## 4. Program output, case A: BALANCED (full JSON from `result_dict`)\n")
    add(
        "Fields to look at: `ranking[].raw`, `normalised`, `score` (higher is always better), "
        "`contribution` (weight x score, exact), `composite` (rounded), `rank`; `selected`; `rejected`; "
        "`explanation`; `advantages_vs_runner_up`; `disadvantages_vs_runner_up`; `baselines`.\n"
    )
    add("```json\n" + run(EXAMPLE_CANDIDATES, req, "BALANCED") + "\n```\n")

    add("### 4b. Same inputs, other presets: winners and composites\n")
    add("| preset | rank 1 | rank 2 | rank 3 |\n|---|---|---|---|")
    for name, w in PRESETS.items():
        r = select(req, EXAMPLE_CANDIDATES, w, DEFAULT_POLICY, preset_name=name)
        cells = [f"{x.candidate.label}: {fmt(x.composite)}" for x in r.ranked]
        add(f"| {name} | " + " | ".join(cells) + " |")
    add("")

    add("## 5. Case B: two extra candidates that must be rejected\n")
    add(
        "Added to the three above: **Oracle Cloud** (health `DOWN`, otherwise attractive: 5 ms latency) and "
        "**TinyCloud** (security 7.5 is below the MEDIUM minimum of 8.0, and its 1 GiB size limit is smaller "
        "than the 10 GiB file). Expected: both rejected with every failing reason listed; the other three "
        "are normalised without them, so the result must equal case A exactly.\n"
    )
    add("```json\n" + run(case_b, req, "BALANCED") + "\n```\n")

    add("## 6. Scoring code (verbatim)\n")
    for rel in CODE_FILES:
        text = (ROOT / rel).read_text(encoding="utf-8")
        add(f"### `{rel}`\n")
        add("```python\n" + text.rstrip() + "\n```\n")

    add("## 7. Direct answers to the logic questions\n")
    add(
        "| Question | Answer | Where in the code | Test that proves it |\n|---|---|---|---|\n"
        "| Does min-max use only eligible providers? | **Yes.** `check_constraints` runs first and splits "
        "`eligible` from `rejected`; `raw`, `normalise` and ranking are built from `eligible` only. A DOWN "
        "provider with extreme values does not change the others' scores. | `select()`, loops over `eligible` | "
        "`test_rejected_candidates_never_take_part_in_ranking_or_normalisation`; case B above equals case A |\n"
        "| Are cost and latency inverted? | **Yes.** `normalise(..., minimise=True)` gives `score = 1 - n` for "
        "storage cost, transfer cost and latency; reliability and security use `score = n`. A higher "
        "composite is always better. | `normalise()` and `MINIMISED` in `models.py` | "
        "`test_minimised_metric_gives_best_value_score_one_and_worst_zero`, "
        "`test_maximised_metric_gives_highest_value_score_one`, and the worked example |\n"
        "| Zero-range case? | When `max == min` (all equal, or one candidate) **every candidate scores 1.0** on "
        "that metric; no division happens. `n` is reported as 0 (minimised) or 1 (maximised). | "
        "`normalise()`, the `if high == low` branch | `test_all_equal_values_do_not_divide_by_zero_and_everyone_"
        "scores_one`, `test_single_candidate_scores_one` |\n"
        "| Is the tie-break deterministic? | **Yes.** Sort key: higher rounded composite, higher security, "
        "higher reliability, lower total cost, lower provider_id, lower region_id. Candidates are first sorted "
        "by (provider_id, region_id), so input order never matters. No randomness anywhere. | `_sort_key`, "
        "`select()` | `test_tie_break_order_security_then_reliability_then_cost_then_ids`, "
        "`test_results_do_not_depend_on_the_order_candidates_are_supplied` (25 shuffles) |\n"
        "| Is size fit scored? | **No**, it is a hard constraint. | `check_constraints()` | "
        "`test_size_fit_is_a_hard_filter_not_a_score` |\n"
        "| Are weights validated? | Non-negative, finite, known names, not all zero; if they do not sum to 1 "
        "they are divided by their sum and a note says so. | `presets.resolve_weights` | "
        "`test_invalid_weights_are_rejected`, `test_override_is_applied_then_normalised_and_the_note_says_so` |\n"
    )
    add("## 8. Known properties a reviewer should be aware of\n")
    add(
        "* **Rank reversal:** min-max scores depend on the set of eligible candidates, so adding or removing "
        "a provider can change relative scores of the others.\n"
        "* The composite is rounded to 6 decimals **before** ranking, so near-equal composites tie and fall "
        "to the tie-break order.\n"
        "* Latency is the median of the latest 20 successful GET probes per region; in the seed these are "
        "simulated values.\n"
        "* Reads are assumed to download the whole file; one PUT per upload; egress price is per region.\n"
    )

    target = ROOT / "docs" / "03-review-package.md"
    target.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {target} ({len(out)} blocks)")


if __name__ == "__main__":
    main()
