SET DEFINE OFF;

CREATE TABLE Users (
    UserID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Name VARCHAR2(100) NOT NULL,
    Email VARCHAR2(150) UNIQUE NOT NULL,
    Role VARCHAR2(20) DEFAULT 'USER',
    CreatedAt TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE Cloud_Providers (
    ProviderID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ProviderName VARCHAR2(50) NOT NULL,
    Region VARCHAR2(50),
    ReliabilityScore NUMBER(5,2),
    SecurityScore NUMBER(5,2)
);

CREATE TABLE Files (
    FileID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    UserID NUMBER NOT NULL,
    FileName VARCHAR2(255) NOT NULL,
    FileSize NUMBER NOT NULL,
    FileType VARCHAR2(50),
    UploadTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    AccessFrequency NUMBER DEFAULT 0,
    SecurityLevel VARCHAR2(20),
    CONSTRAINT fk_file_user
        FOREIGN KEY (UserID)
        REFERENCES Users(UserID)
);

CREATE TABLE Storage_Locations (
    LocationID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FileID NUMBER NOT NULL,
    ProviderID NUMBER NOT NULL,
    Region VARCHAR2(50),
    BucketName VARCHAR2(150),
    ObjectKey VARCHAR2(300),
    StorageClass VARCHAR2(50),
    CONSTRAINT fk_storage_file
        FOREIGN KEY (FileID)
        REFERENCES Files(FileID),
    CONSTRAINT fk_storage_provider
        FOREIGN KEY (ProviderID)
        REFERENCES Cloud_Providers(ProviderID)
);

CREATE TABLE Access_Logs (
    LogID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    FileID NUMBER NOT NULL,
    UserID NUMBER NOT NULL,
    Action VARCHAR2(30) NOT NULL,
    AccessTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    Latency NUMBER(10,2),
    CONSTRAINT fk_log_file
        FOREIGN KEY (FileID)
        REFERENCES Files(FileID),
    CONSTRAINT fk_log_user
        FOREIGN KEY (UserID)
        REFERENCES Users(UserID)
);

