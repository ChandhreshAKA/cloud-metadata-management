    profile_name      VARCHAR2(30)   NOT NULL,
    weights_json      VARCHAR2(500)  NOT NULL,
    chosen_region_id  NUMBER,
    explanation       VARCHAR2(2000) NOT NULL,
    decided_at        TIMESTAMP(6)   DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_selection_decisions PRIMARY KEY (decision_id),
    CONSTRAINT fk_decisions_file FOREIGN KEY (file_id) REFERENCES files (file_id) ON DELETE CASCADE,
