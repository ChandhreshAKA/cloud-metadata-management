-- ---------------------------------------------------------------------
-- Selection configuration: weights (DB enforces they sum to 1) and thresholds
-- ---------------------------------------------------------------------
CREATE TABLE weight_profiles (
    profile_name     VARCHAR2(30)  NOT NULL,
    description      VARCHAR2(200) NOT NULL,
    w_storage_cost   NUMBER(5,4)   NOT NULL,
    w_transfer_cost  NUMBER(5,4)   NOT NULL,
    w_latency        NUMBER(5,4)   NOT NULL,
    w_reliability    NUMBER(5,4)   NOT NULL,
    w_security       NUMBER(5,4)   NOT NULL,
    is_default       CHAR(1)       DEFAULT 'N' NOT NULL,
    CONSTRAINT pk_weight_profiles PRIMARY KEY (profile_name),
    CONSTRAINT ck_weights_range CHECK (w_storage_cost BETWEEN 0 AND 1 AND w_transfer_cost BETWEEN 0 AND 1
                                       AND w_latency BETWEEN 0 AND 1 AND w_reliability BETWEEN 0 AND 1
                                       AND w_security BETWEEN 0 AND 1),
    CONSTRAINT ck_weights_sum CHECK (w_storage_cost + w_transfer_cost + w_latency + w_reliability + w_security = 1),
    CONSTRAINT ck_weights_default CHECK (is_default IN ('Y','N'))
);

CREATE UNIQUE INDEX ux_weights_one_default ON weight_profiles (CASE WHEN is_default = 'Y' THEN 'Y' END);

