-- ---------------------------------------------------------------------
-- Pricing per region and tier (ILLUSTRATIVE unless is_illustrative = 'N')
-- GB means GiB (2^30 bytes) everywhere in this project.
-- ---------------------------------------------------------------------
CREATE TABLE provider_pricing (
    region_id                 NUMBER       NOT NULL,
    tier_code                 VARCHAR2(10) NOT NULL,
    native_class_name         VARCHAR2(40) NOT NULL,
    storage_usd_per_gb_month  NUMBER(10,6) NOT NULL,
    retrieval_usd_per_gb      NUMBER(10,6) NOT NULL,
