    get_usd_per_1k            NUMBER(10,6) NOT NULL,
    min_storage_days          NUMBER(4)    DEFAULT 0 NOT NULL,
    is_illustrative           CHAR(1)      DEFAULT 'Y' NOT NULL,
    CONSTRAINT pk_provider_pricing PRIMARY KEY (region_id, tier_code),
    CONSTRAINT fk_pricing_region FOREIGN KEY (region_id) REFERENCES provider_regions (region_id) ON DELETE CASCADE,
    CONSTRAINT fk_pricing_tier FOREIGN KEY (tier_code) REFERENCES storage_tiers (tier_code),
    CONSTRAINT uq_pricing_native UNIQUE (region_id, native_class_name),
    CONSTRAINT ck_pricing_nonneg CHECK (storage_usd_per_gb_month >= 0 AND retrieval_usd_per_gb >= 0
                                        AND put_usd_per_1k >= 0 AND get_usd_per_1k >= 0),
    CONSTRAINT ck_pricing_days CHECK (min_storage_days >= 0),
    CONSTRAINT ck_pricing_illustrative CHECK (is_illustrative IN ('Y','N'))
