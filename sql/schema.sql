-- ---------------------------------------------------------------------
-- Audit events: append-only (trigger below). target_type/target_id are a
-- deliberate polymorphic reference WITHOUT a foreign key so that history
-- survives purges of the target.
-- ---------------------------------------------------------------------
CREATE TABLE audit_events (
    event_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    event_time     TIMESTAMP(6)  DEFAULT SYSTIMESTAMP NOT NULL,
    actor_user_id  NUMBER,
    event_type     VARCHAR2(30)  NOT NULL,
    target_type    VARCHAR2(20),
    target_id      NUMBER,
    outcome        VARCHAR2(10)  NOT NULL,
    ip_address     VARCHAR2(45),
    details_json   VARCHAR2(2000),
    CONSTRAINT pk_audit_events PRIMARY KEY (event_id),
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_user_id) REFERENCES users (user_id),
    CONSTRAINT ck_audit_type CHECK (event_type IN ('USER_REGISTERED','LOGIN_OK','LOGIN_FAILED','ACCOUNT_LOCKED',
        'ROLE_CHANGED','FILE_UPLOADED','FILE_DELETED','REPLICA_CREATED','FAILOVER_READ',
        'PROVIDER_STATUS_CHANGED','CONFIG_CHANGED','RECOMMENDATION_DECIDED','ACCESS_DENIED')),
    CONSTRAINT ck_audit_target CHECK (target_type IS NULL OR target_type IN
        ('USER','FILE','PROVIDER_REGION','CONFIG','JOB','RECOMMENDATION','SYSTEM')),
    CONSTRAINT ck_audit_outcome CHECK (outcome IN ('SUCCESS','FAILURE','DENIED')),
    CONSTRAINT ck_audit_json CHECK (details_json IS NULL OR details_json IS JSON)
);

CREATE OR REPLACE TRIGGER trg_audit_events_immutable
BEFORE UPDATE OR DELETE ON audit_events
BEGIN
    RAISE_APPLICATION_ERROR(-20001, 'audit_events is append-only: UPDATE and DELETE are not allowed');
END;
