CREATE TABLE selection_candidates (
    decision_id        NUMBER        NOT NULL,
    region_id          NUMBER        NOT NULL,
    excluded_reason    VARCHAR2(200),
    raw_json           VARCHAR2(1000),
    norm_storage_cost  NUMBER(8,6),
    norm_transfer_cost NUMBER(8,6),
    norm_latency       NUMBER(8,6),
    norm_reliability   NUMBER(8,6),
    norm_security      NUMBER(8,6),
    total_score        NUMBER(8,6),
    CONSTRAINT pk_selection_candidates PRIMARY KEY (decision_id, region_id),
    CONSTRAINT fk_candidates_decision FOREIGN KEY (decision_id) REFERENCES selection_decisions (decision_id) ON DELETE CASCADE,
    CONSTRAINT fk_candidates_region FOREIGN KEY (region_id) REFERENCES provider_regions (region_id),
    CONSTRAINT ck_candidates_raw_json CHECK (raw_json IS NULL OR raw_json IS JSON),
    CONSTRAINT ck_candidates_range CHECK (
        COALESCE(norm_storage_cost, 0) BETWEEN 0 AND 1 AND COALESCE(norm_transfer_cost, 0) BETWEEN 0 AND 1
        AND COALESCE(norm_latency, 0) BETWEEN 0 AND 1 AND COALESCE(norm_reliability, 0) BETWEEN 0 AND 1
        AND COALESCE(norm_security, 0) BETWEEN 0 AND 1 AND COALESCE(total_score, 0) BETWEEN 0 AND 1),
    CONSTRAINT ck_candidates_shape CHECK (
        (excluded_reason IS NOT NULL AND total_score IS NULL AND norm_storage_cost IS NULL
            AND norm_transfer_cost IS NULL AND norm_latency IS NULL AND norm_reliability IS NULL AND norm_security IS NULL)
        OR
        (excluded_reason IS NULL AND total_score IS NOT NULL AND norm_storage_cost IS NOT NULL
            AND norm_transfer_cost IS NOT NULL AND norm_latency IS NOT NULL AND norm_reliability IS NOT NULL AND norm_security IS NOT NULL))
);

