"""SQLAlchemy ORM models.

sql/schema.sql stays the single source of truth for the database structure (tables, constraints,
indexes, triggers). These classes only MAP existing tables; the application never calls
`create_all()` against Oracle. Constraints are named exactly as in schema.sql so that an Oracle
error such as ORA-00001 (UQ_USERS_EMAIL) is still translated by app.db.errors.

Columns that only the database manages (failed_login_count, locked_until, created_at) are not
mapped: Oracle fills them from their DEFAULT values and the application does not read them yet.
"""

from __future__ import annotations

from datetime import datetime

from sqlalchemy import DateTime, Identity, Integer, String, UniqueConstraint
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class Base(DeclarativeBase):
    pass


class User(Base):
    """One row per account. Roles live in the `role` column; there are no per-role tables."""

    __tablename__ = "users"
    __table_args__ = (UniqueConstraint("email", name="uq_users_email"),)

    # GENERATED BY DEFAULT AS IDENTITY in Oracle: the ORM omits the column and reads the new id
    # back with RETURNING ... INTO.
    user_id: Mapped[int] = mapped_column(Integer, Identity(always=False), primary_key=True)
    full_name: Mapped[str] = mapped_column(String(100), nullable=False)
    email: Mapped[str] = mapped_column(String(150), nullable=False)
    role: Mapped[str] = mapped_column(String(10), nullable=False)
    password_hash: Mapped[str | None] = mapped_column(String(255))
    account_status: Mapped[str] = mapped_column(String(15), nullable=False)
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime)
